/**
 * WHAT IT DOES:
 * Custom hooks for all ContentIdea data fetching and mutations.
 * Centralizes TanStack Query logic for the ideas feature.
 *
 * WHY IT EXISTS:
 * Keeps components clean by separating data-fetching concerns.
 * Makes it easy to share query keys and invalidation logic.
 *
 * HOW IT CONNECTS:
 * Used by IdeasPage, KanbanBoard, IdeaCard, and IdeaDetailDrawer.
 */

import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { ideaApi, IdeaStatus } from '../../services/api'
import { useWorkspace } from '../workspace/useWorkspace'

// Stable query key factory — all idea queries share this structure
// so invalidation is predictable.
export const ideaKeys = {
  all: (workspaceId: string) => ['ideas', workspaceId] as const,
  byStatus: (workspaceId: string, status: IdeaStatus) =>
    ['ideas', workspaceId, 'status', status] as const,
  detail: (ideaId: string) => ['ideas', 'detail', ideaId] as const,
}

// Column statuses shown on the Kanban board
export const KANBAN_STATUSES: IdeaStatus[] = [
  'DISCOVERED',
  'SCORED',
  'SELECTED',
  'BRIEFED',
  'REJECTED',
]

/**
 * Fetch all ideas for a specific status column.
 * Auto-refreshes every 30s so new AI-generated ideas appear automatically.
 */
export function useIdeasByStatus(status: IdeaStatus) {
  const { currentWorkspace } = useWorkspace()

  return useQuery({
    queryKey: ideaKeys.byStatus(currentWorkspace?.id ?? '', status),
    queryFn: () => ideaApi.getByStatus(status, 0, 50),
    enabled: !!currentWorkspace,
    // Auto-refresh so ideas generated by AI Engine appear without manual reload
    refetchInterval: 30_000,
    select: (res) => res.data.data.content,
  })
}

/**
 * Fetch a single idea by ID (used in the detail drawer).
 */
export function useIdeaDetail(ideaId: string | null) {
  return useQuery({
    queryKey: ideaKeys.detail(ideaId ?? ''),
    queryFn: () => ideaApi.getById(ideaId!),
    enabled: !!ideaId,
    select: (res) => res.data.data,
  })
}

/**
 * Mutation: update an idea's status (Kanban column move or reject/select).
 * Uses optimistic updates for instant UI feedback.
 */
export function useUpdateIdeaStatus() {
  const queryClient = useQueryClient()
  const { currentWorkspace } = useWorkspace()

  return useMutation({
    mutationFn: ({ ideaId, status }: { ideaId: string; status: IdeaStatus }) =>
      ideaApi.updateStatus(ideaId, status),

    // Invalidate all idea status queries so columns re-fetch
    onSuccess: () => {
      KANBAN_STATUSES.forEach((status) => {
        queryClient.invalidateQueries({
          queryKey: ideaKeys.byStatus(currentWorkspace?.id ?? '', status),
        })
      })
    },
  })
}

/**
 * Mutation: trigger AI idea generation for a niche.
 */
export function useTriggerDiscovery() {
  return useMutation({
    mutationFn: ({ nicheId, count }: { nicheId: string; count?: number }) =>
      ideaApi.triggerDiscovery(nicheId, count),
  })
}

/**
 * Mutation: score a single idea using the AI Engine.
 */
export function useScoreIdea() {
  const queryClient = useQueryClient()
  const { currentWorkspace } = useWorkspace()

  return useMutation({
    mutationFn: ({ ideaId, nicheId }: { ideaId: string; nicheId: string }) =>
      ideaApi.scoreIdea(ideaId, nicheId),

    // After scoring, refresh both columns (DISCOVERED and SCORED)
    onSuccess: () => {
      queryClient.invalidateQueries({
        queryKey: ideaKeys.byStatus(currentWorkspace?.id ?? '', 'DISCOVERED'),
      })
      queryClient.invalidateQueries({
        queryKey: ideaKeys.byStatus(currentWorkspace?.id ?? '', 'SCORED'),
      })
    },
  })
}
