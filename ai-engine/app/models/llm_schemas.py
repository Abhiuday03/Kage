"""
LLM Structured Output Schemas

These Pydantic models define the structure we want the LLM to generate.
Modern LLMs (GPT-4o, Claude 3.5+) support structured output modes.

WHY: Structured outputs eliminate parsing errors and ensure consistent data.
     Instead of asking the LLM to "return JSON", we define exact schemas.

HOW: These schemas are passed to the LLM provider to enforce structure.
"""

from typing import List
from pydantic import BaseModel, Field


class GeneratedIdea(BaseModel):
    """
    Schema for a single content idea generated by the LLM.

    The LLM will be instructed to fill this structure.
    """
    title: str = Field(..., description="Compelling, specific content title")
    description: str = Field(..., description="2-3 sentence description of the content concept")
    reasoning: str = Field(..., description="Why this idea resonates with the target audience")


class IdeaGenerationOutput(BaseModel):
    """
    Complete output from the topic discovery agent.

    The LLM generates multiple ideas in one call.
    """
    ideas: List[GeneratedIdea] = Field(..., description="List of generated content ideas")


class IdeaScoreOutput(BaseModel):
    """
    Schema for idea scoring output.

    The LLM evaluates the idea across multiple dimensions.
    """
    trend_score: int = Field(..., ge=0, le=100, description="How trendy/timely is this topic? (0-100)")
    relevance_score: int = Field(..., ge=0, le=100, description="How relevant to the niche? (0-100)")
    engagement_score: int = Field(..., ge=0, le=100, description="Predicted audience engagement (0-100)")
    reasoning: str = Field(..., description="Explanation of the scores")
